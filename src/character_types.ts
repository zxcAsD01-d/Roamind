import type { EffectorName } from './contact_rig';
import type { EngineSnapshot } from './engine_view';

export type GoalStep = { kind: string; status?: string; position?: number[]; heading?: number;
  action?: string; duration?: number; text?: string; direction?: string; timeout?: number;
  targetId?: string; objectId?: string; effector?: EffectorName; operation?: string; amplitude?: number };
export type CharacterGoal = { id: string; title: string; status: string; detail: string; index: number;
  steps: GoalStep[]; createdAt: number; events: { at: number; status: string; detail: string }[] };
export type SpatialExit = { id: string; position: number[]; normal: number[] | null; width: number | null;
  state: 'unconfirmed' | 'observed-opening' | 'narrow' | 'blocked' | 'traversable' | 'crossed';
  traversable: boolean; connectsRegions: boolean; regions: number[]; sources: string[]; crossings: number };
export type ObservedEnclosure = { status: string; scope: string; closedBoundary: boolean; observedAt: number };
export type SpatialRegion = { id: number; center: number[]; area: number; boundary: string; personChecked: boolean;
  connectedRegions?: number[]; exitIds?: string[]; reachableRegionCount?: number; componentId?: number;
  enclosure?: ObservedEnclosure };
export type SpatialBoundary = { start: number[]; end: number[]; regionId: number;
  state: 'supported' | 'uncertain' | 'unknown' | 'opening'; neighborRegion: number | null };
export type SpatialTopology = { currentRegion: number | null; revision?: number;
  regions: SpatialRegion[]; components?: number; reachableRegions?: number[];
  spaces?: { id: number; regionIds: number[]; area: number; enclosure: ObservedEnclosure }[];
  exits?: SpatialExit[]; boundarySegments?: SpatialBoundary[]; boundarySegmentsTruncated?: boolean;
  passages: { position: number[]; kind: string }[];
  doors: { position: number[]; traversable: boolean }[] };
export type BehaviorMemory = { spatialMemory: { position: number[] | null; observedAt: number;
  resolution: number; cells: { open: number; closed: number; uncertain: number };
  knownCells: [number, number, number, (number | null)?][];
  visitedRegions: number; peopleRegions: { position: number[]; seen: number; confidence: number }[];
  floor?: { tiltDeg: number; support: number; residual: number; observedAt: number } | null;
  exitMemory?: { portals: { point: number[]; confidence: number; uncertaintyMeters: number; crossings: number }[];
    crossings: { portalId: number; at: number; arrivalSide: number }[] };
  topology?: SpatialTopology;
  searchCoverage?: { regions: { key: number[]; confirmed: boolean; observedDirections: number[] }[];
    exits: { position: number[]; direction: number; status: string; lookedAt?: number }[] } };
  mission: { phase: string; ready: boolean }; engine?: EngineSnapshot };
